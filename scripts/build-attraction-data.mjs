/**
 * Splits the curated attraction catalog into one JSON file per city (public/data/attractions/<cityId>.json)
 * and writes the guide hero photos (src/app/data/guide-photos.data.ts). Run via `npm run data`.
 * Import-free apart from the city-pages/guide helpers, so the node test can load it directly.
 */
import { mkdirSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { loadCurated } from './city-pages.mjs';
import { CITY_GUIDES } from '../src/app/data/city-guides.data.ts';
import { isGuideAttraction, pickTopSights } from '../src/app/core/seo/city-guide-seo.util.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'public', 'data', 'attractions');
const PHOTOS_TS = join(ROOT, 'src', 'app', 'data', 'guide-photos.data.ts');
const SAFE_ID = /^[a-z0-9_]+$/;

/** Empties outDir, then writes each city's full array as <cityId>.json. Returns the file count. */
export function writeCityFiles(curated, outDir) {
  const ids = Object.keys(curated);
  for (const id of ids) {
    if (!SAFE_ID.test(id)) throw new Error(`unsafe city id: ${id}`);
  }
  mkdirSync(outDir, { recursive: true });
  for (const f of readdirSync(outDir)) unlinkSync(join(outDir, f));
  for (const id of ids) {
    writeFileSync(join(outDir, `${id}.json`), JSON.stringify(curated[id]));
  }
  return ids.length;
}

/** Per guide: the top-rated usable sight's photo. http:// images are dropped first (mixed content). */
export function guideTopPhotos(curated, guides) {
  const out = {};
  for (const { cityId } of guides) {
    const list = (curated[cityId] ?? []).filter((a) => !(a.imageUrl && a.imageUrl.startsWith('http://')));
    const photo = pickTopSights(list.filter(isGuideAttraction), 8).find((s) => s.imageUrl)?.imageUrl;
    if (photo) out[cityId] = photo;
  }
  return out;
}

function writePhotosModule(photos, file) {
  const entries = Object.keys(photos).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(photos[k])},`);
  const src = [
    '// AUTO-GENERATED by scripts/build-attraction-data.mjs — do not hand-edit.',
    'export const GUIDE_TOP_PHOTOS: Record<string, string> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
  writeFileSync(file, src);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const curated = loadCurated();
  const count = writeCityFiles(curated, OUT_DIR);
  writePhotosModule(guideTopPhotos(curated, CITY_GUIDES), PHOTOS_TS);
  console.log(`attraction data: wrote ${count} city files to public/data/attractions/`);
}
